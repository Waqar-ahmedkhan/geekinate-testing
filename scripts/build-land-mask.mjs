// Rasterises Natural Earth's 110m land polygons into the packed equirectangular bitmask the globe samples its dots from.
//
// Run once, by hand, when the mask needs regenerating:
//   node scripts/build-land-mask.mjs .tmp/ne_110m_land.geojson
//
// The output is committed as lib/globe/land.js, so neither the GeoJSON nor this script is part of the build. Shipping the mask
// rather than the polygons is what keeps the runtime free of a point-in-polygon pass and of a 138KB parse on first paint.
//
// Scanline fill, not per-cell point-in-polygon. A cell test against every ring is 131,072 x ~10,000 edge tests; walking each row
// once and XOR-filling the spans between its crossings is the same answer for a fraction of the work, and even-odd across a
// polygon's rings gives holes (the Caspian, the Great Lakes) for free.
import { readFileSync, writeFileSync } from 'node:fs';

const WIDTH = 512;
const HEIGHT = 256;
const SOURCE = process.argv[2] || '.tmp/ne_110m_land.geojson';
const OUT = 'lib/globe/land.js';

// A Polygon is one entry, a MultiPolygon is many. Everything downstream wants the same shape: an array of rings, outer first.
const polygonsOf = ({ type, coordinates }) => (type === 'Polygon' ? [coordinates] : type === 'MultiPolygon' ? coordinates : []);

// Where a ring crosses one horizontal line, in pixel columns. The half-open rule on the y test (one endpoint above, one not) is
// what stops a vertex that lands exactly on the scanline from being counted twice and inverting the rest of the row.
const crossings = (ring, lat) => {
  const hits = [];
  for (let index = 0; index < ring.length - 1; index += 1) {
    const [ax, ay] = ring[index],
      [bx, by] = ring[index + 1];
    if (ay > lat === by > lat) continue;
    const lon = ax + ((lat - ay) / (by - ay)) * (bx - ax);
    hits.push(((lon + 180) / 360) * WIDTH);
  }
  return hits;
};

const geo = JSON.parse(readFileSync(SOURCE, 'utf8'));
const polygons = geo.features.flatMap((feature) => polygonsOf(feature.geometry));
const mask = new Uint8Array(WIDTH * HEIGHT);

for (let row = 0; row < HEIGHT; row += 1) {
  const lat = 90 - ((row + 0.5) / HEIGHT) * 180;
  polygons.forEach((rings) => {
    // Every ring of one polygon into a single sorted list, so an outer ring and the holes inside it resolve as one even-odd run.
    const hits = rings.flatMap((ring) => crossings(ring, lat)).sort((a, b) => a - b);
    for (let pair = 0; pair + 1 < hits.length; pair += 2) {
      const from = Math.max(0, Math.ceil(hits[pair] - 0.5)),
        to = Math.min(WIDTH - 1, Math.floor(hits[pair + 1] - 0.5));
      for (let col = from; col <= to; col += 1) mask[row * WIDTH + col] = 1;
    }
  });
}

// One bit per cell, LSB first inside each byte — the runtime unpacks with the same convention.
const bytes = new Uint8Array((WIDTH * HEIGHT) / 8);
mask.forEach((lit, index) => {
  if (lit) bytes[index >> 3] |= 1 << (index & 7);
});

const land = mask.reduce((total, lit) => total + lit, 0);
const bits = Buffer.from(bytes).toString('base64');
const file = `// GENERATED by scripts/build-land-mask.mjs from Natural Earth 110m land. Do not edit by hand — re-run the script.
//
// An equirectangular land/sea bitmask, one bit per cell, LSB first inside each byte, row 0 at the north pole. ${WIDTH} x ${HEIGHT}
// is a cell of about 0.7 degrees, which resolves every coastline the globe's dots are dense enough to show and costs ${(bytes.length / 1024).toFixed(0)}KB packed.
export const LAND = {
  width: ${WIDTH},
  height: ${HEIGHT},
  bits: '${bits}',
};
`;

writeFileSync(OUT, file);
process.stdout.write(`${land} land cells of ${WIDTH * HEIGHT} (${((land / mask.length) * 100).toFixed(1)}%) -> ${OUT}\n\n`);

// An ASCII proof. A mask with its rows or its longitudes flipped is perfectly plausible as a bitmap and obvious as a map.
const STEP_X = WIDTH / 100,
  STEP_Y = HEIGHT / 40;
for (let row = 0; row < 40; row += 1) {
  let line = '';
  for (let col = 0; col < 100; col += 1) {
    line += mask[Math.floor(row * STEP_Y) * WIDTH + Math.floor(col * STEP_X)] ? '#' : ' ';
  }
  process.stdout.write(`${line}\n`);
}
